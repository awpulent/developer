package com.awpulent.flashrev.demo

import com.awpulent.flashrev.chart.SmParser
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.math.abs

class DemoSongGeneratorTest {

    private val generated by lazy { DemoSongGenerator.generate() }

    @Test
    fun audioHasReasonableLengthAndLevel() {
        val seconds = generated.pcm.size / DemoSongGenerator.SAMPLE_RATE.toDouble()
        assertTrue("duration $seconds", seconds in 50.0..70.0)
        val peak = generated.pcm.maxOf { abs(it.toInt()) }
        assertTrue("peak $peak", peak in 25000..32767)
        // Lead-in should be nearly silent before beat 0 (only the pad swells in).
        val leadInRms = rms(generated.pcm, 0, (0.2 * DemoSongGenerator.SAMPLE_RATE).toInt())
        val bodyRms = rms(generated.pcm, (20.0 * DemoSongGenerator.SAMPLE_RATE).toInt(), (21.0 * DemoSongGenerator.SAMPLE_RATE).toInt())
        assertTrue("lead-in $leadInRms vs body $bodyRms", leadInRms < bodyRms * 0.5)
    }

    @Test
    fun stepFileParsesIntoThreeChartsThatFitTheAudio() {
        val parsed = SmParser.parse(generated.smText)
        assertEquals(DemoSongGenerator.TITLE, parsed.title)
        assertEquals(DemoSongGenerator.AUDIO_FILE, parsed.music)
        assertEquals(3, parsed.charts.size)
        val seconds = generated.pcm.size / DemoSongGenerator.SAMPLE_RATE.toDouble()
        val counts = parsed.charts.map { it.noteCount }
        assertTrue("counts $counts", counts[0] < counts[1] && counts[1] < counts[2])
        assertTrue("easy has enough notes: ${counts[0]}", counts[0] >= 60)
        for (chart in parsed.charts) {
            for (n in chart.notes) {
                assertTrue(n.lane in 0..3)
                assertTrue("note at ${n.time}", n.time >= DemoSongGenerator.LEAD_IN_SECONDS - 1e-9 && n.time < seconds - 1.0)
            }
            // At most a jump (2 lanes) at any moment.
            val perTime = chart.notes.groupBy { it.time }.values.maxOf { it.size }
            assertTrue("max simultaneous $perTime", perTime <= 2)
        }
    }

    @Test
    fun melodyOnsetsLandOnTheSixteenthGrid() {
        val secPerSlot = 60.0 / DemoSongGenerator.BPM / 4
        val parsed = SmParser.parse(generated.smText)
        for (n in parsed.charts.last().notes) {
            val slots = (n.time - DemoSongGenerator.LEAD_IN_SECONDS) / secPerSlot
            assertTrue("off-grid note at ${n.time}", abs(slots - Math.rint(slots)) < 1e-6)
        }
    }

    @Test
    fun deterministic() {
        val a = DemoSongGenerator.generate()
        val b = DemoSongGenerator.generate()
        assertEquals(a.smText, b.smText)
        assertTrue(a.pcm.contentEquals(b.pcm))
    }

    private fun rms(pcm: ShortArray, from: Int, to: Int): Double {
        var sum = 0.0
        for (i in from until to) { val v = pcm[i] / 32768.0; sum += v * v }
        return kotlin.math.sqrt(sum / (to - from))
    }
}
